#!/usr/bin/env python3
"""
Issue #10: turn measured results into docs/paper/results_summary.tex and figures. Never edits numbers;
everything printed comes from the JSON files produced by the benchmark, eval and training scripts.

  python scripts/research_report.py
"""

import argparse
import json
from pathlib import Path
import statistics as st

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402


def ms(xs):
    return f"{st.mean(xs):.1f} $\\pm$ {st.pstdev(xs):.1f}"


def mean_or_na(xs, fmt="{:.3f}"):
    xs = [x for x in xs if x is not None]
    return fmt.format(st.mean(xs)) if xs else "n/a"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ablation", default="docs/paper/data/ablation.json")
    ap.add_argument("--eval", default="splice_benchmark_telemetry.json")
    ap.add_argument("--training", default="splice_head_training_telemetry.json")
    ap.add_argument("--out-dir", default="docs/paper")
    a = ap.parse_args()
    out = Path(a.out_dir); (out / "figures").mkdir(parents=True, exist_ok=True)
    ab = json.loads(Path(a.ablation).read_text())
    ev = json.loads(Path(a.eval).read_text())
    tr = json.loads(Path(a.training).read_text())
    res, ks, ctxs = ab["results"], ab["ks"], ab["contexts"]

    # ---- speedup vs sequence length, mean ± sd across windows, per K
    fig, ax = plt.subplots(figsize=(6.2, 3.8))
    for k in ks + ["batched"]:
        xs, means, sds = [], [], []
        for c in ctxs:
            rows = [r for r in res if r["context"] == c]
            vals = [r["vanilla_ms"] / (r["batched_ms"] if k == "batched" else r["k"][str(k)]["ms"]) for r in rows]
            xs.append(rows[0]["seq_len"]); means.append(st.mean(vals)); sds.append(st.pstdev(vals))
        ax.errorbar(xs, means, yerr=sds, marker="o", capsize=3, linestyle="--" if k == "batched" else "-",
                    label="batched exhaustive (exact, recall 1.00)" if k == "batched" else f"speculative K={k} (recall {mean_or_na([r['k'][str(k)]['recall'] for r in res], '{:.2f}')})")
    ax.set_xlabel("Sequence length (bp)"); ax.set_ylabel("Speedup vs sequential ISM (×)"); ax.set_yscale("log")
    cond = ab.get("conditions") or {}
    where = "" if cond.get("on_ac_power") is None else (", AC power" if cond["on_ac_power"] else ", battery/power-saver")
    ax.set_title(f"Speculative ISM, {ab['gpu']}{where}; {ab['candidates']} candidates/window", fontsize=8); ax.grid(alpha=.3); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig(out / "figures" / "speedup_vs_length.png", dpi=200); plt.close(fig)

    # ---- recall and acceptance vs K (all lengths pooled)
    fig, ax = plt.subplots(figsize=(6.2, 3.6))
    for key, label in (("recall", "recall of high-impact variants"), ("alpha", "acceptance rate α")):
        m, s = [], []
        for k in ks:
            v = [r["k"][str(k)][key] for r in res if r["k"][str(k)][key] is not None]
            m.append(st.mean(v) if v else float("nan")); s.append(st.pstdev(v) if v else 0.0)
        ax.errorbar(ks, m, yerr=s, marker="o", capsize=3, label=label)
    ax.set_xlabel(f"Verification budget K (of {ab['candidates']} candidates)"); ax.set_ylim(0, 1.05); ax.grid(alpha=.3); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(out / "figures" / "recall_alpha_vs_k.png", dpi=200); plt.close(fig)

    # ---- LaTeX
    model = ev["model"].split("/")[-1].replace("_", "\\_")
    cond = ab.get("conditions") or {}
    power = "" if cond.get("on_ac_power") is None else (" Measured on AC power." if cond["on_ac_power"] else
             f" Measured on battery ({cond.get('platform_profile') or 'unknown'} profile); sequential (batch-1) times are inflated by CPU throttling.")
    L = ["% Generated by scripts/research_report.py from measured JSON. Do not edit by hand.", "\\begin{table}[t]\\centering\\small",
         f"\\caption{{Splice-site prediction on held-out test chromosomes (chr1, 3, 5, 7, 9). Frozen {model} + trained head.}}",
         "\\begin{tabular}{lcc}\\toprule & Donor & Acceptor \\\\ \\midrule",
         f"ROC-AUC & {ev['donor_roc_auc']:.4f} & {ev['acceptor_roc_auc']:.4f} \\\\",
         f"PR-AUC & {ev['donor_pr_auc']:.4f} & {ev['acceptor_pr_auc']:.4f} \\\\",
         f"Top-1 accuracy & {ev['donor_top_1_acc']:.3f} & {ev['acceptor_top_1_acc']:.3f} \\\\",
         f"Top-2k accuracy & {ev['donor_top_k_acc']:.3f} & {ev['acceptor_top_k_acc']:.3f} \\\\ \\midrule",
         f"Positions / sites & \\multicolumn{{2}}{{c}}{{{ev['n_total_loci']:,} / {ev['n_donors'] + ev['n_acceptors']:,}}} \\\\",
         "\\bottomrule\\end{tabular}\\end{table}", "",
         "\\begin{table}[t]\\centering\\small",
         f"\\caption{{Speculative in-silico mutagenesis ablation ({ab['windows']} held-out windows per length, {ab['candidates']} candidates each, "
         f"$|\\Delta|\\geq{ab['threshold']}$ is high-impact). Times in ms, mean $\\pm$ s.d.; recall against exhaustive ISM.{power}}}",
         "\\begin{tabular}{rr" + "c" * (2 + len(ks)) + "}\\toprule",
         "Length & & Sequential & Batched & " + " & ".join(f"K={k}" for k in ks) + " \\\\ \\midrule"]
    for c in ctxs:
        rows = [r for r in res if r["context"] == c]
        L.append(f"{rows[0]['seq_len']:,} & time & {ms([r['vanilla_ms'] for r in rows])} & {ms([r['batched_ms'] for r in rows])} & "
                 + " & ".join(ms([r['k'][str(k)]['ms'] for r in rows]) for k in ks) + " \\\\")
        sp = lambda key: f"{st.mean([r['vanilla_ms'] / (r['batched_ms'] if key == 'b' else r['k'][key]['ms']) for r in rows]):.1f}$\\times$"  # noqa: E731
        L.append(f" & speedup & 1.0$\\times$ & {sp('b')} & " + " & ".join(sp(str(k)) for k in ks) + " \\\\")
        L.append(" & recall & 1 & 1 & " + " & ".join(mean_or_na([r['k'][str(k)]['recall'] for r in rows]) for k in ks) + " \\\\ \\addlinespace")
    L += ["\\bottomrule\\end{tabular}\\end{table}", "",
          f"% max |batched - sequential| over all windows: {max(r['max_abs_diff_batched_vs_sequential'] for r in res):.2e} ({ab['dtype']})",
          f"% head training: {tr['steps']} steps, {tr['minutes']} min, best val mean PR-AUC {tr['best_val_mean_pr_auc']:.4f}"]
    (out / "results_summary.tex").write_text("\n".join(L) + "\n")
    print(f"→ {out / 'results_summary.tex'}, figures in {out / 'figures'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
